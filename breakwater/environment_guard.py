"""Hash runtime files from Docker's filesystem export, never from a suspect interpreter.

Exports stream through the trusted controller. No target code is imported and no
archive member is extracted. Bind-mounted task/data state is outside this runtime
inventory; those inputs have separate seals and read-only mount checks.
"""
import hashlib
import json
import os
from pathlib import Path, PurePosixPath
import subprocess
import tarfile

VERSION = 'breakwater-runtime-inventory-v1'
PACKAGES = ('torch', 'transformers', 'sglang', 'triton', 'numpy', 'ray', 'datasets',
            'safetensors', 'megatron', 'transformer_engine', 'apex', 'flashinfer')
FIXED_ROOTS = ['/etc', '/usr', '/bin', '/sbin', '/lib', '/lib64', '/opt', '/root', '/sgl-workspace',
               '/home/author/.local/lib', '/home/author/.local/bin',
               '/home/worker/.local/lib', '/home/worker/.local/bin']
# Codex's root-owned author policy is generated by bootstrap, not part of the
# runtime/package image. It is intentionally absent from the evaluation container.
EXCLUDES = ['/etc/hostname', '/etc/hosts', '/etc/resolv.conf', '/etc/codex', '/opt/environment-baseline']
# Controller-owned read-only bind targets. Docker creates their (empty) mountpoint
# directories in a started container's root filesystem, so a stage that mounts one of
# them would otherwise differ from a stage that does not. Their contents are trusted
# host mounts with their own provenance, never image or agent state.
TRUSTED_MOUNTS = ['/opt/breakwater', '/opt/breakwater-drivers', '/opt/breakwater-worker',
                  '/opt/breakwater-cell']


class RuntimeMismatch(ValueError):
    pass


HOOKS = ('sitecustomize', 'usercustomize')
DEFAULT_SHADOW = {'packages': list(PACKAGES), 'hooks': list(HOOKS), 'environments': True}


def shadow_policy(extra=None):
    """Task-declared decoy policy; the default covers every listed package, both hooks and environment markers."""
    policy = {'packages': list(PACKAGES), 'hooks': list(HOOKS), 'environments': True}
    if extra:
        if set(extra) - {'packages', 'extra_packages', 'hooks', 'environments'}:
            raise RuntimeMismatch('Unknown workspace shadow policy field')
        if 'packages' in extra:
            policy['packages'] = list(extra['packages'])
        policy['packages'] = sorted(set(policy['packages']) | set(extra.get('extra_packages', [])))
        if 'hooks' in extra:
            policy['hooks'] = list(extra['hooks'])
        if 'environments' in extra:
            policy['environments'] = bool(extra['environments'])
    for name in policy['packages'] + policy['hooks']:
        if not isinstance(name, str) or not name.isidentifier():
            raise RuntimeMismatch('Invalid package or hook name in shadow policy')
    return policy


def describe(container, workdir, packages=PACKAGES, shadow=None):
    # Called exactly once, BEFORE untrusted authoring. Its results are subsequently
    # fixed inputs to the external scanner, never rediscovered in the modified target.
    program = '''import importlib.util,json,sys,sysconfig
from pathlib import Path
names=json.loads(sys.argv[1]); roots=list(sys.path)+list(sysconfig.get_paths().values())
origins={}
for name in names:
 spec=importlib.util.find_spec(name)
 if spec is not None:
  paths=list(spec.submodule_search_locations or [])
  if spec.origin and spec.origin not in ('built-in','frozen'):paths.append(str(Path(spec.origin).parent))
  paths=[str(Path(value).resolve()) for value in paths]
  roots.extend(paths);origins[name]=paths
print(json.dumps({'roots':roots,'packages':origins,'interpreter':sys.executable}))
'''
    packages = sorted(set(packages) | set((shadow or DEFAULT_SHADOW)['packages']))
    result = subprocess.run(['docker', 'exec', '--user=0', container, 'python3', '-I', '-B', '-c', program,
                             json.dumps(packages)], capture_output=True, check=True)
    value = json.loads(result.stdout)
    roots = set(FIXED_ROOTS)
    for root in value['roots']:
        if not isinstance(root, str) or not root.startswith('/'):
            continue
        path = PurePosixPath(root)
        if str(path) == workdir or str(path).startswith(workdir.rstrip('/') + '/'):
            continue  # Task-owned mini_slime/model implementations remain editable.
        if str(path) != '/' and '..' not in path.parts:
            roots.add(str(path))
    spec = {'version': VERSION, 'roots': sorted(roots), 'excludes': EXCLUDES + TRUSTED_MOUNTS,
            'package_origins': value['packages'], 'interpreter': value['interpreter']}
    if shadow is not None:
        # Recorded in the sealed baseline so the verifier applies the identical policy.
        spec['shadow'] = shadow
    return spec


def selected(name, spec):
    path = '/' + str(PurePosixPath(name))
    if any(path == root or path.startswith(root.rstrip('/') + '/') for root in spec['excludes']):
        return False
    return any(path == root or path.startswith(root.rstrip('/') + '/') for root in spec['roots'])


def scan(container, spec):
    """Works on stopped containers. An altered .pth/hashlib/python cannot fake this."""
    if spec.get('version') != VERSION:
        raise RuntimeMismatch('Unknown runtime inventory protocol')
    process = subprocess.Popen(['docker', 'export', container], stdout=subprocess.PIPE, stderr=subprocess.PIPE)
    files = {}
    try:
        with tarfile.open(fileobj=process.stdout, mode='r|*') as archive:
            for member in archive:
                path = PurePosixPath(member.name)
                if path.is_absolute() or '..' in path.parts:
                    raise RuntimeMismatch('Unsafe path in runtime export')
                name = str(path)
                if not selected(name, spec):
                    continue
                if name in files:
                    raise RuntimeMismatch('Duplicate runtime export entry: ' + name)
                record = {'mode': member.mode & 0o7777, 'uid': member.uid, 'gid': member.gid}
                if member.isfile():
                    sha = hashlib.sha256()
                    with archive.extractfile(member) as stream:
                        for chunk in iter(lambda: stream.read(8 * 1024**2), b''):
                            sha.update(chunk)
                    record.update(kind='file', bytes=member.size, sha256=sha.hexdigest())
                elif member.isdir():
                    record.update(kind='directory')
                elif member.issym() or member.islnk():
                    record.update(kind='symlink' if member.issym() else 'hardlink', target=member.linkname)
                else:
                    raise RuntimeMismatch('Special file in runtime/package roots: ' + name)
                files[name] = record
        if process.wait(timeout=30) != 0:
            raise RuntimeMismatch('Could not independently export runtime filesystem')
    finally:
        if process.poll() is None:
            process.kill()
            process.wait()
        process.stdout.close()
        process.stderr.close()
    if not files:
        raise RuntimeMismatch('Empty runtime inventory')
    return files


def compare(expected, actual, *, fresh_runtime=False):
    aliases = {}
    if fresh_runtime:
        # Native NVIDIA CDI creates one random-named loader config per role.
        # Compare full bytes/ownership/mode, preserving ordering roles. This is
        # allowed only across fresh containers, never for the post-agent check.
        import re
        actual = dict(actual)
        for role in ('00', 'zz'):
            pattern = re.compile(r'etc/ld\.so\.conf\.d/' + role + r'-nvcr-\d+\.conf')
            before = [name for name in expected if pattern.fullmatch(name)]
            after = [name for name in actual if pattern.fullmatch(name)]
            if len(before) == len(after) == 1 and expected[before[0]] == actual[after[0]]:
                if before[0] != after[0]:
                    aliases[after[0]] = before[0]
                    actual[before[0]] = actual.pop(after[0])
    missing = sorted(set(expected) - set(actual))
    added = sorted(set(actual) - set(expected))
    changed = sorted(key for key in set(expected) & set(actual) if expected[key] != actual[key])
    return {'status': 'FAIL' if missing or added or changed else 'PASS',
            'missing': missing, 'added': added, 'changed': changed, 'files_checked': len(expected),
            'runtime_generated_aliases': aliases}


def importable_name(filename):
    """The top-level module a file directly on ``sys.path`` provides (source, bytecode or extension)."""
    for suffix in ('.py', '.pyc'):
        if filename.endswith(suffix):
            return filename[:-len(suffix)]
    if filename.endswith('.so'):
        return filename.split('.', 1)[0]
    return None


def shadows(workspace, policy=None, excludes=(), links=None):
    """Catch workspace copies that impersonate fixed dependencies or install import hooks.

    Only import-reachable decoys count: a top-level ``<package>.py`` (or bytecode or
    extension module) and every file of a top-level ``<package>/`` package that has an
    ``__init__`` module, because the workdir is the directory trusted runners put on
    ``sys.path``. A same-named directory or file deeper in the tree (``kernels/triton/``,
    a ``datasets/`` data folder) is not import-reachable and is not flagged. Startup hooks
    (``sitecustomize``/``usercustomize`` anywhere, ``.pth`` files in a site directory) and
    virtual-environment markers are flagged wherever they are. ``excludes`` are
    workspace-relative paths that the sealed snapshot leaves out.

    Symbolic links count like files at their own path, because an evaluation stage may
    recreate them: links on disk are found in the tree, and ``links`` (relative path ->
    link text) supplies the ones a snapshot recorded instead of copying. A link named
    like a protected package at the top level, or inside a top-level package directory,
    is a decoy. A flagged link's value is its link text.
    """
    policy = policy or DEFAULT_SHADOW
    packages, hooks = set(policy['packages']), set(policy['hooks'])
    root = Path(workspace)
    def excluded(rel):
        return any(rel == item or rel.startswith(item.rstrip('/') + '/') for item in excludes)
    found = {path.relative_to(root).as_posix(): os.readlink(path) for path in root.rglob('*') if path.is_symlink()}
    found = {rel: text for rel, text in found.items() if not excluded(rel)}
    found.update(links or {})
    reachable = {child.name for child in root.iterdir()
                 if child.name in packages and child.is_dir() and not child.is_symlink()
                 and any(importable_name(entry.name) == '__init__' and entry.is_file() and not entry.is_symlink()
                         for entry in child.iterdir())}
    reachable |= {PurePosixPath(rel).parts[0] for rel in found
                  if len(PurePosixPath(rel).parts) > 1 and PurePosixPath(rel).parts[0] in packages}
    result = {}
    for path in root.rglob('*'):
        if not path.is_file() or path.is_symlink():
            continue
        rel = path.relative_to(root)
        if excluded(rel.as_posix()):
            continue
        decoy = (importable_name(path.name) in packages) if len(rel.parts) == 1 else rel.parts[0] in reachable
        site = any(part in ('site-packages', 'dist-packages') for part in rel.parts[:-1])
        hook = path.name.split('.', 1)[0] in hooks or (bool(hooks) and path.suffix == '.pth' and site)
        # A new virtualenv cannot smuggle an alternate dependency tree into evaluation.
        environment = policy['environments'] and (
            path.name == 'pyvenv.cfg' or any(part in ('site-packages', 'dist-packages') for part in rel.parts))
        if decoy or hook or environment:
            value = hashlib.sha256()
            with path.open('rb') as stream:
                for chunk in iter(lambda: stream.read(1024**2), b''):
                    value.update(chunk)
            result[rel.as_posix()] = value.hexdigest()
    for rel, text in sorted(found.items()):
        parts = PurePosixPath(rel).parts
        name = parts[-1]
        decoy = (name in packages or importable_name(name) in packages) if len(parts) == 1 else parts[0] in reachable
        site = any(part in ('site-packages', 'dist-packages') for part in parts[:-1])
        hook = name.split('.', 1)[0] in hooks or (bool(hooks) and name.endswith('.pth') and site)
        environment = policy['environments'] and (
            name == 'pyvenv.cfg' or any(part in ('site-packages', 'dist-packages') for part in parts))
        if decoy or hook or environment:
            result[rel] = 'symlink:' + text
    return result
