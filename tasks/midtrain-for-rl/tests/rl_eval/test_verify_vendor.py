"""Vendor integrity remains strict after pip's editable install writes metadata."""
import hashlib
import json
from pathlib import Path
import tempfile
import unittest

from verify_vendor import verify


class VendorTests(unittest.TestCase):
    def setUp(self):
        self.directory = tempfile.TemporaryDirectory()
        self.addCleanup(self.directory.cleanup)
        self.root = Path(self.directory.name)
        self.vendor = self.root / 'vendor/slime'
        self.vendor.mkdir(parents=True)
        self.source = self.vendor / 'train.py'
        self.source.write_text('print("pinned training source")\n')
        validator = self.root / 'checkpoint_check.py'
        validator.write_text('# pinned checkpoint validator\n')
        (self.root / 'vendor_manifest.json').write_text(json.dumps({
            'sha256': {'vendor/slime/train.py': hashlib.sha256(self.source.read_bytes()).hexdigest()},
            'checkpoint_validator': {'sha256': hashlib.sha256(validator.read_bytes()).hexdigest()},
        }))

    def test_clean_and_editable_installed_source_match(self):
        self.assertEqual(verify(self.root), 1)
        metadata = self.vendor / 'slime.egg-info'
        metadata.mkdir()
        for name in ('PKG-INFO', 'SOURCES.txt', 'requires.txt', 'top_level.txt'):
            (metadata / name).write_text('generated by editable installation\n')
        cache = self.vendor / '__pycache__'
        cache.mkdir()
        (cache / 'train.cpython-312.pyc').write_bytes(b'compiled bytecode')
        self.assertEqual(verify(self.root), 1)

    def test_changed_source_is_rejected_after_editable_install(self):
        (self.vendor / 'slime.egg-info').mkdir()
        self.source.write_text('# modified\n')
        with self.assertRaisesRegex(RuntimeError, r'changed.*vendor/slime/train.py'):
            verify(self.root)

    def test_missing_source_is_rejected(self):
        self.source.unlink()
        with self.assertRaisesRegex(RuntimeError, r'missing.*vendor/slime/train.py'):
            verify(self.root)

    def test_unexpected_source_is_rejected(self):
        (self.vendor / 'wall_clock 2.py').write_text('# unexpected copy\n')
        with self.assertRaisesRegex(RuntimeError, r'unexpected.*vendor/slime/wall_clock 2.py'):
            verify(self.root)

    def test_nested_metadata_name_does_not_hide_source(self):
        extra = self.vendor / 'slime' / 'slime.egg-info'
        extra.mkdir(parents=True)
        (extra / 'extra.py').write_text('# unexpected source\n')
        with self.assertRaisesRegex(RuntimeError, r'unexpected.*extra.py'):
            verify(self.root)

    def test_changed_checkpoint_validator_is_rejected(self):
        (self.root / 'checkpoint_check.py').write_text('# modified validator\n')
        with self.assertRaisesRegex(RuntimeError, 'checkpoint validator'):
            verify(self.root)


if __name__ == '__main__':
    unittest.main()
